-- Baseline for a fresh PostgreSQL database. Objects are owned by the migration role.

CREATE SEQUENCE public.member_number_seq
    START WITH 10000
    INCREMENT BY 1
    NO CYCLE;

CREATE TABLE public.members (
    id uuid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    email varchar(255) NOT NULL,
    first_name varchar(255),
    last_name varchar(255),
    member_number bigint NOT NULL,
    qr_token varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT members_pkey PRIMARY KEY (id),
    CONSTRAINT uk9d30a9u1qpg8eou0otgkwrp5d UNIQUE (email),
    CONSTRAINT ukp460vvkqycaeesx0wici54pg3 UNIQUE (qr_token),
    CONSTRAINT ukt5yl7apmx6ff543irne5m2mcw UNIQUE (member_number),
    CONSTRAINT members_status_check CHECK (
        status::text = ANY (ARRAY['ACTIVE'::varchar, 'INACTIVE'::varchar, 'BANNED'::varchar]::text[])
    )
);

CREATE TABLE public.app_users (
    id uuid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    enabled boolean NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    member_id uuid NOT NULL,
    CONSTRAINT app_users_pkey PRIMARY KEY (id),
    CONSTRAINT ukqkweruflsfa061tq673soanm3 UNIQUE (member_id),
    CONSTRAINT app_users_role_check CHECK (
        role::text = ANY (ARRAY['STAFF'::varchar, 'ADMIN'::varchar]::text[])
    ),
    CONSTRAINT fk7t6womejfj554dbibpiv9uv4j FOREIGN KEY (member_id) REFERENCES public.members (id)
);

CREATE TABLE public.event (
    id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.event_id_seq),
    cover_required boolean NOT NULL,
    ends_at timestamp(6) without time zone,
    location varchar(255),
    membership_required boolean NOT NULL,
    name varchar(255),
    starts_at timestamp(6) without time zone,
    status varchar(255),
    CONSTRAINT event_pkey PRIMARY KEY (id),
    CONSTRAINT event_location_check CHECK (location = 'OUTLAND'),
    CONSTRAINT event_status_check CHECK (
        status::text = ANY (ARRAY['ACTIVE'::varchar, 'ARCHIVED'::varchar]::text[])
    )
);

CREATE TABLE public.check_in (
    id uuid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    event_id bigint,
    method varchar(255) NOT NULL,
    received_at timestamp(6) with time zone NOT NULL,
    checked_in_by_id uuid NOT NULL,
    member_id uuid NOT NULL,
    CONSTRAINT check_in_pkey PRIMARY KEY (id),
    CONSTRAINT check_in_method_check CHECK (
        method::text = ANY (ARRAY['QR_SCAN'::varchar, 'MANUAL'::varchar]::text[])
    ),
    CONSTRAINT fk5vvsyhptscjk6x72garoxr1k2 FOREIGN KEY (member_id) REFERENCES public.members (id),
    CONSTRAINT fkqgi5i9fry3md06eous2dwux8e FOREIGN KEY (checked_in_by_id) REFERENCES public.app_users (id)
);

CREATE TABLE public.member_note (
    id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.member_note_id_seq),
    content varchar(2000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    created_by_id uuid NOT NULL,
    member_id uuid NOT NULL,
    CONSTRAINT member_note_pkey PRIMARY KEY (id),
    CONSTRAINT fk2bpvucml8pj0buo2ikykwoboy FOREIGN KEY (member_id) REFERENCES public.members (id),
    CONSTRAINT fk4q6qke3yjt9pr65awfd7t7r7y FOREIGN KEY (created_by_id) REFERENCES public.app_users (id)
);

CREATE TABLE public.memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.memberships_id_seq),
    created_at timestamp(6) with time zone NOT NULL,
    program varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    type varchar(255) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    valid_from timestamp(6) with time zone NOT NULL,
    valid_until timestamp(6) with time zone,
    created_by uuid,
    member_id uuid NOT NULL,
    CONSTRAINT memberships_pkey PRIMARY KEY (id),
    CONSTRAINT uq_memberships_member_program_type UNIQUE (member_id, program, type),
    CONSTRAINT memberships_program_check CHECK (program = 'OUTLAND'),
    CONSTRAINT memberships_status_check CHECK (
        status::text = ANY (ARRAY['ACTIVE'::varchar, 'EXPIRE'::varchar, 'CANCELLED'::varchar]::text[])
    ),
    CONSTRAINT memberships_type_check CHECK (
        type::text = ANY (ARRAY['PAID'::varchar, 'FREE'::varchar]::text[])
    ),
    CONSTRAINT fkkv2gm8d7nl8u1nrfvxt6tbwhc FOREIGN KEY (member_id) REFERENCES public.members (id),
    CONSTRAINT fkrlc3pwkv6owjlv0uhmvergpvd FOREIGN KEY (created_by) REFERENCES public.app_users (id)
);
